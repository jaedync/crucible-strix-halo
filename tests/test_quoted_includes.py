"""Check that quoted includes in tracked C and HIP sources resolve to tracked files.

A clean clone holds only tracked files. A quoted include that resolves only to an
untracked file builds on a dirty checkout and fails on a clean clone.
"""
import fnmatch
import posixpath
import re
import subprocess
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE_PATTERNS = ("*.h", "*.hip", "*.inc", "*.cpp", "*.cc", "*.cu")
QUOTED_INCLUDE = re.compile(r'^\s*#\s*include\s*"([^"]+)"', re.MULTILINE)
MAKE_INCLUDE_DIR = re.compile(r"-I(\S+)")
# tests/test_gen_cli_cpu.py compiles these files with "-I build -I engine". build/ is generated, so only
# the engine/ headers resolve to tracked files.
GENERATED_TEST_FILES = ("tests/gen_cli_cpu_test.cpp", "tests/gen_jobs_cpu_test.cpp", "tests/gen_cli_cpu_fixture.h")
GENERATED_TEST_DIRS = ("build", "engine")

# Each key is a tracked file, or a directory prefix ending in "/". Every key must
# still match an unresolved include, or the test fails. A fixed file therefore
# cannot keep its exemption.
EXEMPT = {
    "tests/gen_cli_cpu_test.cpp": "gen_cli_cpu.h is generated by tests/test_gen_cli_cpu.py",
    "tests/gen_jobs_cpu_test.cpp": "gen_cli_cpu.h is generated by tests/test_gen_cli_cpu.py",
    "bench/split2048.hip": "split2048_prompt.h is generated by tools/split2048_probe.py; make binaries filters this file out",
}


def git_files(*patterns):
    # A git archive has no .git. Every file in an archive is tracked, so the tree is the tracked set.
    if not (ROOT / ".git").exists():
        return tree_files(*patterns)
    result = subprocess.run(
        ["git", "ls-files", "-z", "--", *patterns], cwd=ROOT, check=True,
        stdout=subprocess.PIPE, text=True,
    )
    return [name for name in result.stdout.split("\0") if name]


def tree_files(*patterns):
    names = [path.relative_to(ROOT).as_posix() for path in ROOT.rglob("*") if path.is_file()]
    if not patterns:
        return names
    # fnmatch lets "*" cross "/", as git pathspecs do by default.
    return [name for name in names if any(fnmatch.fnmatchcase(name, pattern) for pattern in patterns)]


def repo_include_dirs():
    # Only repo-relative -I paths can resolve to tracked files. Makefile
    # variables such as $(ROCM_PATH) point outside the repo and are skipped.
    makefile = (ROOT / "Makefile").read_text(encoding="utf-8")
    dirs = [posixpath.normpath(path) for path in MAKE_INCLUDE_DIR.findall(makefile) if "$" not in path]
    return [path for path in dirs if not path.startswith(("/", ".."))]


def resolves(source, name, tracked, include_dirs):
    # Same search order as the compiler: the including directory, then the -I
    # paths. The compiler does not search the working directory for quoted includes.
    bases = [posixpath.dirname(source), *include_dirs]
    return any(posixpath.normpath(posixpath.join(base, name)) in tracked for base in bases)


def exempt_entry(source):
    for entry in EXEMPT:
        if source == entry or (entry.endswith("/") and source.startswith(entry)):
            return entry
    return None


def unresolved(source, tracked, include_dirs):
    dirs = [*include_dirs, *GENERATED_TEST_DIRS] if source in GENERATED_TEST_FILES else include_dirs
    text = (ROOT / source).read_text(encoding="utf-8", errors="replace")
    for match in QUOTED_INCLUDE.finditer(text):
        if not resolves(source, match.group(1), tracked, dirs):
            # Count from the name. The match can start on a blank line above the include.
            line = text.count("\n", 0, match.start(1)) + 1
            yield f'{source}:{line}: #include "{match.group(1)}"'


class QuotedIncludeTests(unittest.TestCase):
    def test_quoted_includes_resolve_to_tracked_files(self):
        tracked = set(git_files())
        include_dirs = repo_include_dirs()
        missing, used = [], set()
        for source in git_files(*SOURCE_PATTERNS):
            for report in unresolved(source, tracked, include_dirs):
                entry = exempt_entry(source)
                if entry is None:
                    missing.append(report)
                else:
                    used.add(entry)
        stale = sorted(set(EXEMPT) - used)
        self.assertEqual(missing, [], "quoted includes with no tracked target:\n" + "\n".join(missing))
        self.assertEqual(stale, [], "exemptions with no unresolved include (remove them): " + ", ".join(stale))

    def test_split2048_is_not_a_make_binary(self):
        # Its generated header is not tracked, so make binaries must not build it.
        makefile = (ROOT / "Makefile").read_text(encoding="utf-8")
        hip_sources = [line for line in makefile.splitlines() if line.startswith("HIP_SOURCES :=")]
        self.assertEqual(len(hip_sources), 1)
        self.assertIn("filter-out", hip_sources[0])
        self.assertIn("bench/split2048.hip", hip_sources[0])


if __name__ == "__main__":
    unittest.main()
