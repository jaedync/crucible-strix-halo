"""YaRN RoPE tables for the engine: JSON snapshots and engine/layers/rope_tables.h.

`snapshot` (needs CPU torch, see README.md) writes yarn<F>-reference.json for factors 2 and 4 from
reference.frequency_table (the Hugging Face arithmetic). `header` writes the C++ header from the
snapshots; it needs no torch. tests/test_yarn_rope_header.py checks that the committed header equals
the rendered snapshots, so the engine tables are the reference bits.
"""
import argparse
import copy
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = ROOT / "tools" / "yarn"
HEADER = ROOT / "engine" / "layers" / "rope_tables.h"
FACTORS = (2, 4)  # RopeMode::Yarn2, RopeMode::Yarn4 (engine/runtime/rope_mode.h)


def snapshot_path(factor):
    return HERE / f"yarn{factor}-reference.json"


def f32_bits(value):
    return struct.unpack("<I", struct.pack("<f", value))[0]


def hex_float(value):
    """The float32 value of VALUE as an exact C++ hex float literal (0x1.356656p-1f): no decimal rounding, and code to
    the leak guard (a uint32 word list is a number list to its tree scan)."""
    mantissa, exponent = struct.unpack("<f", struct.pack("<f", value))[0].hex().split("p")
    mantissa = mantissa.rstrip("0").rstrip(".")
    return f"{mantissa}p{exponent}f"


def render(snapshots):
    """Header text for {factor: snapshot}. Each table is 32 inverse frequencies, then the multiplier as float32."""
    lines = [
        "// Generated by tools/yarn/rope_header.py from tools/yarn/yarn<F>-reference.json. Do not edit.",
        "// YaRN tables (Hugging Face transformers 4.57.1 arithmetic, original 262,144, beta_fast 32, beta_slow 1):",
        "// 32 float32 inverse frequencies, then the float32 cos/sin multiplier, as exact hex floats. Row i is RopeMode i + 1.",
        "#pragma once",
        "namespace crucible {",
        f"constexpr int kYarnTables = {len(snapshots)};",
        "constexpr int kRopeTableModes = kYarnTables + 1;  // plain, then the YaRN rows (engine/runtime/rope_mode.h RopeMode)",
        "constexpr float kYarnTable[kYarnTables][33] = {",
    ]
    for factor in sorted(snapshots):
        snap = snapshots[factor]
        values = list(snap["inv_freq"]) + [snap["attention_factor"]]
        if len(values) != 33:
            raise ValueError(f"factor {factor}: expected 32 frequencies")
        words = [hex_float(v) for v in values]
        lines.append(f"  {{  // factor {factor}, multiplier {snap['attention_factor']!r}")
        for start in range(0, 33, 6):
            lines.append("    " + ", ".join(words[start:start + 6]) + ",")
        lines.append("  },")
    lines += ["};", "}  // namespace crucible", ""]
    return "\n".join(lines)


def load_snapshots():
    return {f: json.loads(snapshot_path(f).read_text()) for f in FACTORS}


def make_snapshot(factor):
    import torch
    import transformers

    from tools.yarn import reference

    config = json.loads((HERE / "qwen38-rope-config.json").read_text())
    config = copy.deepcopy(config)
    config["text_config"]["rope_scaling"]["factor"] = float(factor)
    inv, scale = reference.frequency_table(config, enabled=True)
    return dict(inv_freq=inv.tolist(), attention_factor=scale, enabled=True, factor=factor,
                transformers_version=transformers.__version__, torch_version=torch.__version__)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["snapshot", "header", "check"])
    args = parser.parse_args()
    if args.action == "snapshot":
        for factor in FACTORS:
            path = snapshot_path(factor)
            if path.exists():
                print(f"keep {path.name}")
                continue
            path.write_text(json.dumps(make_snapshot(factor), indent=2) + "\n")
            print(f"wrote {path.name}")
    elif args.action == "header":
        HEADER.write_text(render(load_snapshots()))
        print(f"wrote {HEADER.relative_to(ROOT)}")
    else:
        same = HEADER.read_text() == render(load_snapshots())
        print("ROPE HEADER SAME" if same else "ROPE HEADER DIFFERS")
        raise SystemExit(0 if same else 1)


if __name__ == "__main__":
    main()
