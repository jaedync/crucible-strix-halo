# The client text for an engine rejection: the cause is only in the server log.
IMAGE_FAILED = "An image of this request changed or was removed before the engine read it. Retry the request."
ENGINE_REJECTED = "The engine rejected this request. The crucible_engine_error line in the server log has the cause."


class ProtocolError(RuntimeError):
    """A server-side failure with a fixed text that the server wrote; the worker log may show it."""


def loggable(text):
    if not isinstance(text, str):
        return "other"
    if text in KNOWN:
        return text
    for prefix in PREFIXES:
        if text.startswith(prefix) and _SUFFIX.fullmatch(text[len(prefix):]):
            return text
    return "other"
